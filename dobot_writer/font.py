# Acentos (marcas combinantes Unicode), desenhados relativamente a uma
# letra de largura 4 e reescalados para a largura real do glifo.
ACCENTS = {
    "́": [[(1.5, 6.8), (2.5, 7.8)]],                       # agudo  á
    "̀": [[(1.5, 7.8), (2.5, 6.8)]],                       # grave  à
    "̂": [[(1, 6.8), (2, 7.8), (3, 6.8)]],                 # circunflexo â
    "̃": [[(0.8, 7), (1.5, 7.6), (2.5, 7), (3.2, 7.6)]],   # til    ã
    "̈": [[(1, 7.2), (1.3, 7.2)], [(2.7, 7.2), (3, 7.2)]],  # trema  ü
    "̧": [[(2, 0), (2, -0.6), (2.8, -1), (1.8, -1.6)]],    # cedilha ç
}

UNKNOWN = "?"


def glyph(char):
    """Devolve (largura, traços) para um carácter, incluindo acentos."""
    decomposed = unicodedata.normalize("NFD", char.upper())
    base, marks = decomposed[:1], decomposed[1:]
    width, strokes = GLYPHS.get(base, GLYPHS[UNKNOWN])
    strokes = [list(s) for s in strokes]
    for mark in marks:
        k = width / 4.0
        for accent in ACCENTS.get(mark, []):
            strokes.append([(x * k, y) for x, y in accent])
    return width, strokes
